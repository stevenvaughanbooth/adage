#!/usr/bin/env node
// Embeds the built map (dist/) into the adage binary: copies each file to
// crates/adage-cli/assets/map/ with brotli (.br) and gzip (.gz) variants where compression helps,
// and generates crates/adage-cli/src/map/assets_list.rs (path, content type, include_bytes!).
//
// The file as is is embedded only when it is small or does not compress (fonts); the server
// answers every browser with br or gzip. Output is deterministic (sorted, no timestamps), so
// `pnpm drift` can check the committed copy. Budget: 400 KB brotli for the page, excluding the
// layout worker (elkjs), which loads lazily.

import { brotliCompressSync, constants, gzipSync } from "node:zlib";
import { mkdirSync, readdirSync, readFileSync, rmSync, statSync, writeFileSync } from "node:fs";
import { dirname, join, relative, sep } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const web = join(here, "..");
const repo = join(web, "..", "..");
const dist = join(web, "dist");
const out = join(repo, "crates", "adage-cli", "assets", "map");
const list = join(repo, "crates", "adage-cli", "src", "map", "assets_list.rs");
const BUDGET = 400 * 1024;
const RAW_MAX = 4 * 1024;

const TYPES = {
  ".html": "text/html; charset=utf-8",
  ".js": "text/javascript; charset=utf-8",
  ".css": "text/css; charset=utf-8",
  ".woff2": "font/woff2",
  ".svg": "image/svg+xml",
  ".json": "application/json",
  ".txt": "text/plain; charset=utf-8",
  ".png": "image/png",
  ".ico": "image/x-icon",
};

function walk(dir) {
  return readdirSync(dir)
    .flatMap((f) => {
      const p = join(dir, f);
      return statSync(p).isDirectory() ? walk(p) : [p];
    })
    .sort();
}

function gzip(buf) {
  const z = gzipSync(buf, { level: 9 });
  z[9] = 0xff; // OS: unknown, the same on every platform
  return z;
}

function brotli(buf, text) {
  return brotliCompressSync(buf, {
    params: {
      [constants.BROTLI_PARAM_QUALITY]: 11,
      [constants.BROTLI_PARAM_MODE]: text ? constants.BROTLI_MODE_TEXT : constants.BROTLI_MODE_GENERIC,
      [constants.BROTLI_PARAM_SIZE_HINT]: buf.length,
    },
  });
}

rmSync(out, { recursive: true, force: true });
const entries = [];
let pageBr = 0;
let workerBr = 0;
const rows = [];
for (const file of walk(dist)) {
  const path = relative(dist, file).split(sep).join("/");
  const ext = path.slice(path.lastIndexOf("."));
  const type = TYPES[ext];
  if (!type) throw new Error(`no content type for ${path}`);
  const raw = readFileSync(file);
  const text = type.startsWith("text/") || type.includes("json") || type.includes("svg");
  const br = brotli(raw, text);
  const gz = gzip(raw);
  const keepBr = br.length < raw.length * 0.95;
  const keepGz = gz.length < raw.length * 0.95;
  const keepRaw = !keepBr || !keepGz || raw.length <= RAW_MAX || path === "index.html";
  const dest = join(out, path);
  mkdirSync(dirname(dest), { recursive: true });
  if (keepRaw) writeFileSync(dest, raw);
  if (keepBr) writeFileSync(`${dest}.br`, br);
  if (keepGz) writeFileSync(`${dest}.gz`, gz);
  const wire = keepBr ? br.length : raw.length;
  if (path.includes("layout.worker")) workerBr += wire;
  else pageBr += wire;
  rows.push([path, raw.length, keepBr ? br.length : null, keepGz ? gz.length : null, keepRaw]);
  const inc = (suffix) => `Some(include_bytes!("../../assets/map/${path}${suffix}"))`;
  entries.push(
    `    Asset {\n        path: ${JSON.stringify(path)},\n        content_type: ${JSON.stringify(type)},\n        immutable: ${path.startsWith("assets/")},\n` +
      `        raw: ${keepRaw ? inc("") : "None"},\n        br: ${keepBr ? inc(".br") : "None"},\n        gz: ${keepGz ? inc(".gz") : "None"},\n    },`,
  );
}

writeFileSync(
  list,
  `// @generated by web/map/scripts/embed.mjs from web/map/dist (pnpm assets). Do not edit.\n` +
    `pub(crate) static ASSETS: &[Asset] = &[\n${entries.join("\n")}\n];\n`,
);

const kb = (n) => (n === null ? "—" : `${(n / 1024).toFixed(1)} KB`);
for (const [p, raw, br, gz, keep] of rows) {
  console.log(`${p.padEnd(58)} raw ${kb(raw).padStart(10)}${keep ? "" : " (not embedded)"}  br ${kb(br).padStart(9)}  gz ${kb(gz).padStart(9)}`);
}
console.log(`page, brotli: ${kb(pageBr)} of the ${kb(BUDGET)} budget; layout worker (elkjs, lazy): ${kb(workerBr)}`);
if (pageBr > BUDGET) {
  console.error(`over budget by ${kb(pageBr - BUDGET)}`);
  process.exit(1);
}
