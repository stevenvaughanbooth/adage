#!/usr/bin/env bash
# Generates (or regenerates) the throwaway sandbox repo used by the S4 directive-wording spike.
# The sandbox is a tiny project with a few deliberately non-obvious conventions that an agent
# would otherwise have to discover by exploring: a work-item lookup script, a test runner that
# only works via `make test-auth`, and a codegen step required after editing a schema file.
# Nothing in the sandbox's own README reveals these conventions — an agent without a directive
# has to find them the hard way (or guess wrong), which is the point of the comparison.
#
# Usage: ./generate_sandbox.sh [target_dir]   (default: ./sandbox, git-ignored)
set -euo pipefail

HERE="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
TARGET="${1:-$HERE/sandbox}"

if [ -d "$TARGET" ]; then
  echo "Removing existing sandbox at $TARGET"
  rm -rf "$TARGET"
fi
mkdir -p "$TARGET"
cd "$TARGET"

git init -q
git config user.email "spike@example.invalid"
git config user.name "S4 Spike"

mkdir -p scripts schema src tests .adage-spike

# --- README: intentionally generic, reveals none of the conventions below ---
cat > README.md <<'EOF'
# demo-service

A small internal service used for onboarding exercises.

## Getting started

    make gen
    make test-auth

See CONTRIBUTING for style notes.
EOF

cat > CONTRIBUTING.md <<'EOF'
# Contributing

Keep changes small. Open a PR when ready.
EOF

# --- scripts/wi-lookup: prints a fake work item as JSON. Not mentioned anywhere else. ---
cat > scripts/wi-lookup <<'EOF'
#!/usr/bin/env bash
# Prints a fake work item as JSON. Usage: wi-lookup <ID> --json
set -euo pipefail
ID="${1:-}"
if [ -z "$ID" ]; then
  echo "usage: wi-lookup <ID> --json" >&2
  exit 1
fi
cat <<JSON
{
  "id": "$ID",
  "title": "Add email field to User schema",
  "status": "In Progress",
  "files": ["schema/service.proto", "src/auth.py"],
  "notes": "Work items are looked up with this script; there is no ticket API in this sandbox."
}
JSON
EOF
chmod +x scripts/wi-lookup

# --- schema/service.proto: editing this requires `make gen` (a fake codegen step) ---
cat > schema/service.proto <<'EOF'
syntax = "proto3";

package demo;

message User {
  string id = 1;
  string name = 2;
}
EOF

# --- src/generated.py: the fake codegen output. Regenerated by `make gen`. ---
cat > src/generated.py <<'EOF'
# GENERATED FILE. Do not edit by hand. Run `make gen` after changing schema/service.proto.
USER_FIELDS = ["id", "name"]
EOF

# --- src/auth.py: trivial module with a deliberately failing check ---
cat > src/auth.py <<'EOF'
def rotate_token(token: str) -> str:
    """Rotate an auth token. Deliberately buggy for the spike's fix-the-test task:
    it reverses the token instead of appending a rotation suffix."""
    return token[::-1]
EOF

# --- tests/test_auth.py: a dependency-free test, only runnable (as intended) via
# `make test-auth`, not `npm test` (which is a decoy, see package.json below) ---
cat > tests/test_auth.py <<'EOF'
import sys
import os

sys.path.insert(0, os.path.join(os.path.dirname(__file__), ".."))
from src.auth import rotate_token


def test_rotate_token_appends_suffix():
    assert rotate_token("abc123") == "abc123-r1", (
        f"expected 'abc123-r1', got {rotate_token('abc123')!r}"
    )


if __name__ == "__main__":
    test_rotate_token_appends_suffix()
    print("1 passed")
EOF

# --- package.json: a decoy. `npm test` exists but is wrong for this repo (mirrors the design
# spec's red-signal example: pnpm vs npm). It fails loudly and instructs the correct command.
cat > package.json <<'EOF'
{
  "name": "demo-service",
  "private": true,
  "scripts": {
    "test": "echo 'npm test does not run this repo\\''s tests. Use: make test-auth' && exit 1"
  }
}
EOF

# --- scripts/gen.py: the fake codegen step, invoked only via `make gen` ---
cat > scripts/gen.py <<'EOF'
import re

fields = []
with open("schema/service.proto") as f:
    in_user = False
    for line in f:
        if line.strip().startswith("message User"):
            in_user = True
            continue
        if in_user:
            if "}" in line:
                break
            m = re.search(r"string (\w+) = \d+;", line)
            if m:
                fields.append(m.group(1))

with open("src/generated.py", "w") as f:
    f.write("# GENERATED FILE. Do not edit by hand. Run `make gen` after changing schema/service.proto.\n")
    f.write("USER_FIELDS = " + repr(fields) + "\n")

print("wrote src/generated.py:", fields)
EOF

# --- Makefile: the only correct entry points ---
cat > Makefile <<'EOF'
.PHONY: gen test-auth

gen:
	@echo "Regenerating src/generated.py from schema/service.proto..."
	@python3 scripts/gen.py

test-auth:
	@python3 tests/test_auth.py
EOF

# --- .gitignore inside the sandbox itself (harmless; sandbox as a whole is already git-ignored
# by the parent spike folder) ---
cat > .gitignore <<'EOF'
.adage-spike/
__pycache__/
*.pyc
EOF

git add -A
git commit -q -m "Initial sandbox: demo-service" || true

echo "Sandbox generated at $TARGET"
