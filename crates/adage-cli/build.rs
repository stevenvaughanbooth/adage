//! Embeds the Claude Code plugin's own files (`plugin/claude-code`: `hooks.json`, the mod's
//! modules, the session-start shim, `plugin.json`, its types and README) into the `adage` binary,
//! so `adage init` can stage the plugin as a local marketplace from any install of this binary:
//! a checkout build, `cargo install --git`, the release installers, npm (`src/claude_plugin.rs`).
//! Left out: `dist/` (the bundled binaries: `adage init` copies the running ones), the mod's tests
//! and their fixtures, and `VALIDATE.txt` (CI's record of `claude plugin validate`).
//!
//! It also passes on the target triple this binary is built for (`ADAGE_BUILD_TARGET`), which
//! names the `dist/<target>/` directory the shim looks in.

use std::path::{Path, PathBuf};

/// The plugin's directory, relative to this crate.
const PLUGIN: &str = "../../plugin/claude-code";

/// Whether a file of the plugin travels with the binary (`rel` uses `/`).
fn included(rel: &str) -> bool {
    let name = rel.rsplit('/').next().unwrap_or(rel);
    !(rel.starts_with("dist/")
        || rel.split('/').any(|c| c == "node_modules" || c == "fixtures")
        || name.ends_with(".test.ts")
        || name.ends_with(".test.tsx")
        || name == "VALIDATE.txt"
        || name == ".DS_Store")
}

fn walk(root: &Path, dir: &Path, out: &mut Vec<(String, PathBuf, bool)>) {
    let Ok(rd) = std::fs::read_dir(dir) else { return };
    for e in rd.flatten() {
        let p = e.path();
        let rel = p.strip_prefix(root).unwrap_or(&p).to_string_lossy().replace('\\', "/");
        if p.is_dir() {
            if rel != "dist" && included(&format!("{rel}/")) {
                walk(root, &p, out);
            }
        } else if included(&rel) {
            out.push((rel.clone(), p.clone(), executable(&p) || rel.starts_with("scripts/")));
        }
    }
}

#[cfg(unix)]
fn executable(p: &Path) -> bool {
    use std::os::unix::fs::PermissionsExt;
    std::fs::metadata(p).is_ok_and(|m| m.permissions().mode() & 0o111 != 0)
}

#[cfg(not(unix))]
fn executable(_: &Path) -> bool {
    false
}

fn main() {
    let manifest = PathBuf::from(std::env::var_os("CARGO_MANIFEST_DIR").expect("cargo sets CARGO_MANIFEST_DIR"));
    let out_dir = PathBuf::from(std::env::var_os("OUT_DIR").expect("cargo sets OUT_DIR"));
    let target = std::env::var("TARGET").unwrap_or_default();
    println!("cargo:rustc-env=ADAGE_BUILD_TARGET={target}");
    println!("cargo:rerun-if-changed=build.rs");
    let root = manifest.join(PLUGIN);
    let mut files = Vec::new();
    if root.is_dir() {
        // Each entry but dist/: staging binaries there must not rebuild adage. Cargo scans a
        // directory given here recursively.
        for e in std::fs::read_dir(&root).into_iter().flatten().flatten() {
            if e.file_name() != "dist" {
                println!("cargo:rerun-if-changed={}", e.path().display());
            }
        }
        walk(&root, &root, &mut files);
    } else {
        // Built outside the repository (no plugin beside it): `adage init` then says the plugin
        // cannot be staged from this binary and names the marketplace instead.
        println!("cargo:rerun-if-changed={}", root.display());
    }
    files.sort();
    let mut src = String::from(
        "// @generated by crates/adage-cli/build.rs from plugin/claude-code. Do not edit.\n\
         pub(crate) static FILES: &[Embedded] = &[\n",
    );
    for (rel, path, exec) in &files {
        let abs = path.canonicalize().unwrap_or_else(|_| path.clone());
        src.push_str(&format!(
            "    Embedded {{ path: {rel:?}, bytes: include_bytes!({:?}), executable: {exec} }},\n",
            abs.to_string_lossy()
        ));
    }
    src.push_str("];\n");
    std::fs::write(out_dir.join("plugin_files.rs"), src).expect("writing plugin_files.rs");
}
