"""Public fixture definitions. Keep this directory outside the model's filesystem mounts."""
import json

ORIGIN = "https://github.com/adage-evals/cardinal"
REPO_KEY = "github.com/adage-evals/cardinal"
SPLITS = {"train": 8, "dev": 2, "test": 4}
FAMILIES = ("manifest", "layout", "control")


def tasks():
    return [{"id": f"{split}-{family}-{index:02d}", "split": "diagnostic", "pool": split,
             "family": family, "variant": index,
             # New IDs and numbers do not make a template an independent task group.
             "semantic_group": f"cardinal/{family}-v1",
             "evidence_kind": "synthetic_within_template"}
            for split, count in SPLITS.items() for family in FAMILIES
            for index in range(1, count + 1)]


def task(task_id):
    for value in tasks():
        if value["id"] == task_id:
            return value
    raise ValueError(f"unknown task: {task_id}")


def dump(value):
    return json.dumps(value, indent=2, sort_keys=True) + "\n"


def catalog(spec, solved=False):
    value = {"currency": "USD", "products": {"basic": 1200, "pro": 2400, "team": 4800}}
    if solved:
        value["products"]["pro"] = 2500 + spec["variant"] * 37
    return value


def generated(value):
    return "# Generated by tools/catalog.py; update catalog/prices.json instead.\nPRICES = " + repr(dict(sorted(value["products"].items()))) + "\n"


