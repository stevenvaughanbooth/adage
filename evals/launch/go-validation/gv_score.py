#!/usr/bin/env python3
"""Score a GO-validation family sandbox (the live runner's `score` command), outside the agent's view.

  python3 gv_score.py <task-id> <dir> [--keep-env]

The task is done when the project's CI would accept it and the deliverables the prompt names exist.
Checks, in order (all must hold for `passed`):

  lint            `eslint .` and `prettier -c src test`: the project's `pnpm lint` (CI's first step),
                  run before the hidden test file is written
  docs_readme     the README the agent left has the utility's reference heading (### `name(`)
  docs_generated  after the project's own generator (`automd`, which `pnpm build` runs) regenerates
                  the README from the sources, the heading is still there: the utility is documented
                  where the README's reference comes from (its JSDoc), so the docs survive the next build
  own_test        a test file the agent added or changed under test/ names the utility
  tests           `vitest run --typecheck` exits 0 with tests run: the whole suite, the agent's tests
                  and the hidden behaviour test (test/zz-rw-hidden.test.ts: the export and every
                  example of the prompt)

Prints JSON: passed, checks, hidden_failed (the hidden test's failing cases), suite_failed (other
failing test files), n_tests, changed_files, tails. Then prunes node_modules (disk), as RepoBench's
scorer does. No tokens.
"""

from __future__ import annotations

import json
import os
import re
import subprocess
import sys
import time
from pathlib import Path

HERE = Path(__file__).resolve().parent
os.environ.setdefault("REPOBENCH_CACHE", "/tmp/adage-launch/go-validation/cache")
sys.path.insert(0, str(HERE))
sys.path.insert(0, str(HERE.parents[1] / "repobench"))
import common  # noqa: E402
import score as rb_score  # noqa: E402
from sandbox import run_steps  # noqa: E402

import family_ufo as fam  # noqa: E402


def sh(cmd: list[str], d: Path, timeout: int = 180) -> tuple[int, str]:
    try:
        out = subprocess.run(cmd, cwd=d, capture_output=True, text=True, timeout=timeout, env=rb_score.common_env())
        return out.returncode, out.stdout + "\n" + out.stderr
    except subprocess.TimeoutExpired:
        return -9, "TIMEOUT"
    except OSError as e:
        return -1, str(e)


def tail(text: str, n: int = 15) -> str:
    return "\n".join(text.strip().splitlines()[-n:])


def score(tid: str, d: Path) -> dict:
    v = fam.variant(tid)
    r = common.repo(fam.FAMILY["repo"])
    d = Path(d)
    changed = rb_score.changed_files(d, {fam.HIDDEN_PATH})
    bins = d / "node_modules" / ".bin"
    rescue_error = None
    if not (bins / "vitest").exists():  # the agent removed or broke node_modules: reinstall, as CI does
        try:
            run_steps(r.get("setup", []), d)
        except Exception as e:  # noqa: BLE001
            rescue_error = str(e)[:300]
    checks: dict[str, bool] = {}
    t0 = time.time()
    # 1. lint (before the hidden test exists, so only the agent's code is linted)
    c1, lint_out = sh([str(bins / "eslint"), "."], d)
    c2, fmt_out = sh([str(bins / "prettier"), "-c", "src", "test"], d)
    checks["lint"] = c1 == 0 and c2 == 0
    # 2. docs as left by the agent
    readme = d / "README.md"
    heading = fam.readme_heading(v)
    checks["docs_readme"] = readme.exists() and heading in readme.read_text(errors="replace")
    # 3. own test
    own = False
    for p in changed:
        if p.startswith("test/") and p != fam.HIDDEN_PATH and (d / p).is_file():
            if re.search(r"\b" + re.escape(v["name"]) + r"\b", (d / p).read_text(errors="replace")):
                own = True
                break
    checks["own_test"] = own
    # 4. docs regenerated by the project's generator
    c3, automd_out = sh([str(bins / "automd")], d, timeout=120)
    checks["docs_generated"] = c3 == 0 and readme.exists() and heading in readme.read_text(errors="replace")
    # 5. the whole suite with the hidden behaviour test
    (d / fam.HIDDEN_PATH).write_text(fam.hidden(v))
    c4, text = sh([str(bins / "vitest"), "run", "--typecheck", "--reporter=default", "--no-color"], d, timeout=240)
    n = rb_score.count_tests("typescript", text)
    checks["tests"] = c4 == 0 and bool(n)
    hidden_name = Path(fam.HIDDEN_PATH).name
    failed_lines = re.findall(r"^\s*(?:FAIL|×|✗)\s+(.+?)\s*$", text, re.M)
    hidden_failed = sorted({x for x in failed_lines if hidden_name in x or "RWHidden" in x})
    suite_failed = sorted({x for x in failed_lines if x not in hidden_failed})[:20]
    if c4 != 0 and not failed_lines:
        suite_failed = ["(collection, typecheck or setup failure)"]
    return {"passed": all(checks.values()), "hidden_passed": checks["tests"] and not hidden_failed,
            "ci_passed": checks["lint"] and checks["tests"], "checks": checks,
            "n_tests": n, "elapsed_s": round(time.time() - t0, 2),
            "hidden_failed": hidden_failed, "suite_failed": suite_failed, "changed_files": changed[:50],
            "rescue_error": rescue_error, "lint_tail": tail(lint_out + fmt_out, 12), "tail": tail(text)}


def main(argv=None) -> int:
    argv = sys.argv[1:] if argv is None else argv
    keep = "--keep-env" in argv
    argv = [a for a in argv if a != "--keep-env"]
    if len(argv) != 2:
        raise SystemExit("usage: gv_score.py <task-id> <dir> [--keep-env]")
    d = Path(argv[1])
    print(json.dumps(score(argv[0], d)))
    if not keep:
        rb_score.prune(d, common.repo(fam.FAMILY["repo"]).get("prune", ()))
    return 0


if __name__ == "__main__":
    sys.exit(main())
