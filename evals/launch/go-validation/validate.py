#!/usr/bin/env python3
"""Validate every variant's hidden check, as RepoBench's validate.py does for mined fixes: on the
untouched base it must FAIL, with the gold patch (function + JSDoc, a test, README regenerated by
automd, prettier-formatted) it must PASS, and the whole check must run in reasonable time. No tokens.

  python3 validate.py [--only SUBSTR] [--out validation.json] [--work DIR]
"""

from __future__ import annotations

import argparse
import json
import shutil
import sys
import time
from pathlib import Path

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE))
import family_ufo as fam  # noqa: E402
import gv_sandbox  # noqa: E402
import gv_score  # noqa: E402


def main(argv=None) -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--only")
    ap.add_argument("--out", default=str(HERE / "validation.json"))
    ap.add_argument("--work", default="/tmp/adage-launch/go-validation/validate")
    a = ap.parse_args(argv)
    work = Path(a.work)
    rows = []
    for tid in fam.order():
        if a.only and a.only not in tid:
            continue
        d = work / "repo"
        t0 = time.time()
        gv_sandbox.create(tid, d)
        base = gv_score.score(tid, d)
        gv_sandbox.create(tid, d)
        fam.gold(fam.variant(tid), d)
        gold = gv_score.score(tid, d)
        ok = (not base["passed"]) and gold["passed"]
        row = {"task": tid, "split": "train" if tid in fam.train_tasks() else "held-out", "ok": ok,
               "base_passed": base["passed"], "base_checks": base["checks"], "base_hidden_failed": len(base["hidden_failed"]),
               "gold_passed": gold["passed"], "gold_checks": gold["checks"], "gold_n_tests": gold["n_tests"],
               "gold_check_seconds": gold["elapsed_s"], "wall_seconds": round(time.time() - t0, 1)}
        if not gold["passed"]:
            row["gold_tail"] = gold["tail"]
            row["gold_lint_tail"] = gold["lint_tail"]
            row["gold_failed"] = gold["hidden_failed"] + gold["suite_failed"]
        rows.append(row)
        print(json.dumps(row), flush=True)
        shutil.rmtree(d, ignore_errors=True)
    out = {"family": fam.FAMILY_ID, "repo": "unjs/ufo", "base": fam.UFO_BASE, "variants": rows,
           "valid": sum(r["ok"] for r in rows), "of": len(rows)}
    if not a.only:
        Path(a.out).write_text(json.dumps(out, indent=1) + "\n")
    print(f"{out['valid']} of {out['of']} variants valid")
    return 0 if out["valid"] == out["of"] else 1


if __name__ == "__main__":
    sys.exit(main())
