CODEGEN = r'''#!/usr/bin/env node
// Generates src/generated/registry.mjs from registry/*.csv.
//   node tools/codegen.mjs            write it
//   node tools/codegen.mjs --verify   fail if it is out of date
//   node tools/codegen.mjs --root DIR work on another checkout
import { existsSync, readFileSync, readdirSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const args = process.argv.slice(2);
const at = args.indexOf("--root");
const root = at >= 0 ? args[at + 1] : join(dirname(fileURLToPath(import.meta.url)), "..");
const OUT = "src/generated/registry.mjs";

function parse(text) {
  const lines = text.split(/\r?\n/).filter((l) => l.trim() !== "");
  const header = lines[0].split(",").map((h) => h.trim());
  const rows = {};
  for (const line of lines.slice(1)) {
    const cells = line.split(",").map((c) => c.trim());
    const rec = {};
    header.forEach((h, i) => {
      const v = cells[i] ?? "";
      if (h !== "code") rec[h] = /^[0-9]+$/.test(v) ? Number(v) : v;
    });
    rows[cells[0].toUpperCase()] = rec;
  }
  return rows;
}

function render() {
  const dir = join(root, "registry");
  const files = readdirSync(dir).filter((f) => f.endsWith(".csv")).sort();
  const out = ["// Generated by tools/codegen.mjs from registry/*.csv. Do not edit by hand.", "",
    "export const TABLES = Object.freeze({"];
  for (const f of files) {
    const rows = parse(readFileSync(join(dir, f), "utf8"));
    out.push(`  ${JSON.stringify(f.slice(0, -4))}: Object.freeze({`);
    for (const code of Object.keys(rows).sort()) {
      const rec = rows[code];
      const fields = Object.keys(rec).sort().map((k) => `${JSON.stringify(k)}: ${JSON.stringify(rec[k])}`).join(", ");
      out.push(`    ${JSON.stringify(code)}: Object.freeze({ ${fields} }),`);
    }
    out.push("  }),");
  }
  out.push("});", "");
  return out.join("\n");
}

const text = render();
const target = join(root, OUT);
if (args.includes("--verify")) {
  if (!existsSync(target) || readFileSync(target, "utf8") !== text) {
    console.error(`error: ${OUT} is out of date with registry/*.csv, run npm run codegen`);
    process.exit(1);
  }
} else {
  writeFileSync(target, text);
  console.log(`wrote ${OUT}`);
}
'''

LOOKUP = r'''#!/usr/bin/env node
// Look up an item in @@phrase@@:  @@usage@@ <ID> [--json]
import { readFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { inflateSync } from "node:zlib";

const root = join(dirname(fileURLToPath(import.meta.url)), @@up@@);
const args = process.argv.slice(2);
const ids = args.filter((a) => !a.startsWith("-"));
if (ids.length !== 1) {
  console.error("usage: @@usage@@ <ID> [--json]");
  process.exit(2);
}

function load() {
  const buf = readFileSync(join(root, "@@store@@"));
  if (buf.subarray(0, 4).toString("latin1") !== "@@magic@@") throw new Error("@@usage@@: unreadable store");
  return JSON.parse(inflateSync(buf.subarray(4)).toString("utf8"));
}

function wrap(text, width = 88) {
  const out = [];
  let line = "";
  for (const word of text.split(/\s+/).filter(Boolean)) {
    if (line && line.length + word.length + 1 > width) {
      out.push(line);
      line = word;
    } else {
      line = line ? `${line} ${word}` : word;
    }
  }
  if (line) out.push(line);
  return out.length ? out : [""];
}

function sortKeys(value) {
  if (Array.isArray(value)) return value.map(sortKeys);
  if (value && typeof value === "object") {
    return Object.fromEntries(Object.keys(value).sort().map((k) => [k, sortKeys(value[k])]));
  }
  return value;
}

const key = ids[0].trim().toUpperCase();
const item = load().find((x) => x.id === key);
if (!item) {
  console.error(`@@usage@@: no item ${key} in @@phrase@@`);
  process.exit(1);
}
if (args.includes("--json")) {
  console.log(JSON.stringify(sortKeys(item), null, 2));
} else {
  const out = [
    `${item.id}  ${item.title}`,
    `status: ${item.status}   priority: ${item.priority}   area: ${item.area}   reported: ${item.reported} by ${item.reporter}`,
    "",
    ...wrap(item.description),
    "",
    "Acceptance:",
    ...wrap(item.acceptance).map((l) => `  ${l}`),
    "",
    "Files:",
    ...(item.files.length ? item.files.map((f) => `  ${f}`) : ["  (none)"]),
  ];
  console.log(out.join("\n"));
}
'''

ALIAS_HOOKS = r'''// Resolves @@scope@@/* to src/* (the path alias in jsconfig.json). Node does not read jsconfig.json;
// the suite preloads this hook through tools/testing/setup.mjs.
import { existsSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";

const PREFIX = "@@scope@@/";
const SRC = @@src@@;

export function resolve(specifier, context, nextResolve) {
  if (specifier.startsWith(PREFIX)) {
    const file = join(SRC, specifier.slice(PREFIX.length));
    if (existsSync(file)) return { url: pathToFileURL(file).href, shortCircuit: true };
  }
  return nextResolve(specifier, context);
}
'''

REGISTER = r'''import * as nodeModule from "node:module";
import { resolve } from "@@hooks@@";

if (typeof nodeModule.registerHooks === "function") {
  nodeModule.registerHooks({ resolve });
} else {
  nodeModule.register(new URL("@@hooks@@", import.meta.url));
}
'''


class NodeNpm(Stack):
    NAME = "node-npm"
    LANG = "js"
    DEAD_END_MODES = ("path_alias", "env_guard", "wrong_runner")

    verify_cmd = "npm run check"
    regen_cmd = "npm run codegen"
    instinct_cmd = "npm test"

    def fn(self, snake):
        return bugs.camel(snake)

    @property
    def fixtures_global(self):
        return f"__{self.skin.pkg}Fixtures"

    # ------------------------------------------------------------------ naming

    def module_path(self, module):
        return f"src/{module}.mjs"

    def reader_path(self):
        return f"src/{self.skin.registry_module}.mjs"

    def generated_path(self):
        return "src/generated/registry.mjs"

    def spec_for(self, rel_from_src, importer_dir="src"):
        """How a source file imports another file under src/: through the alias, or relatively."""
        if self.conv.dead_end == "path_alias":
            return f"{self.skin.scope}/{rel_from_src}"
        if importer_dir == "src":
            return f"./{rel_from_src}"
        return f"../src/{rel_from_src}"

    # ------------------------------------------------------------------ commands and signatures

    def dead_end_runner(self):
        return "node --test"

    def dead_end_variants(self):
        return ["node --test", "node --test test/", "node --test test/*.test.mjs"]

    def dead_end_signature(self):
        mode = self.conv.dead_end
        if mode == "path_alias":
            return f"Cannot find package '{self.skin.scope}'"
        if mode == "env_guard":
            return f"{self.skin.env} is not set, run the suite with npm run check"
        return "the test fixtures are not loaded, this suite runs through npm run check"

    def dead_end_notes(self):
        mode = self.conv.dead_end
        if mode == "path_alias":
            return (f"Sources and tests import {self.skin.scope}/*, an alias in jsconfig.json that Node resolves only "
                    f"through the hook `npm run check` preloads (--import ./tools/testing/setup.mjs). Plain "
                    f"`node --test` fails with ERR_MODULE_NOT_FOUND. The working command is declared in .ci/pipeline.yml.")
        if mode == "env_guard":
            return (f"Test files import tools/testing/env.mjs, which throws unless {self.skin.env}=test (set only by "
                    f"`npm run check`). The working command is declared in .ci/pipeline.yml.")
        return ("Test files import tools/testing/fixtures.mjs, which throws unless the fixtures were preloaded by "
                "`npm run check` (--import ./tools/testing/setup.mjs), so any generic runner fails. The working "
                "command is declared in .ci/pipeline.yml.")

    def instinct_signature(self):
        return "error: npm test is retired here, the suite runs with npm run check"

    def stale_signature(self):
        return f"error: {self.generated_path()} is out of date with registry/*.csv, run npm run codegen"

    def decoy_command(self, mode):
        name = self.skin.decoys[mode]
        return {"unused_target": f"npm run {name}", "lookalike_regen": "npm run gen:docs",
                "lookalike_verify": f"npm run {name}", "legacy_script": f"node tools/{name}.mjs"}[mode]

    # ------------------------------------------------------------------ files

    def fill_tool(self, text, **extra):
        sk = self.skin
        return bugs.fill(text, phrase=sk.tracker_phrase, usage=sk.tool.rsplit("/", 1)[-1], store=sk.store,
                         magic=sk.magic, scope=sk.scope, **extra)

    def module_text(self, module):
        ids = self.plan.layout[module]
        head = f"// {module.capitalize()} helpers for {self.skin.repo}.\n"
        if "ci_lookup" in ids:
            head += f'import {{ normalizeCode }} from "{self.spec_for("util.mjs")}";\n'
        funcs = [self.function_code(t, t in self.plan.bugged) for t in ids]
        return head + "\n" + "\n".join(funcs)

    def reader_text(self):
        sk = self.skin
        out = ["// Registry lookups. The tables live in registry/*.csv; this module reads the generated copy.",
               f'import {{ TABLES }} from "{self.spec_for("generated/registry.mjs")}";',
               f'import {{ normalizeCode }} from "{self.spec_for("util.mjs")}";', ""]
        out += ["function row(table, code) {", "  const found = TABLES[table][normalizeCode(code)];",
                "  if (!found) throw new Error(`unknown ${table} code: ${code}`);", "  return { ...found };", "}", ""]
        for tab in sk.tables:
            out += [f"export function {self.fn(tab.noun)}(code) {{", f'  return row("{tab.name}", code);', "}", ""]
        return "\n".join(out)

    def test_head(self, module_rel):
        c = self.conv
        out = ['import test from "node:test";', 'import assert from "node:assert/strict";']
        if c.dead_end == "env_guard":
            out.append('import "../tools/testing/env.mjs";')
        elif c.dead_end == "wrong_runner":
            out.append('import "../tools/testing/fixtures.mjs";')
        out.append(f'import * as m from "{self.spec_for(module_rel, importer_dir="test")}";')
        return out

    def indent(self, body, n=2):
        return "\n".join((" " * n + line) if line else "" for line in body.splitlines())

    def test_text(self, module):
        out = self.test_head(f"{module}.mjs") + ["", f'test("{module} loads", () => {{',
                                                 "  assert.ok(Object.keys(m).length > 0);", "});"]
        for t in self.plan.layout[module]:
            if t in self.plan.bugged:
                continue
            out += ["", f'test("{self.fname(t)}", () => {{', self.indent(self.test_body(t)), "});"]
        return "\n".join(out) + "\n"

    def reader_test_text(self):
        sk = self.skin
        out = self.test_head(f"{sk.registry_module}.mjs")
        for tab in sk.tables:
            row = self.stable_row(tab)
            out += ["", f'test("{self.fn(tab.noun)}", () => {{', f"  const row = m.{self.fn(tab.noun)}({json.dumps(row[0].lower())});"]
            for c, v in zip(tab.columns[1:], row[1:]):
                out.append(f"  assert.equal(row.{c}, {json.dumps(self.typed(v))});")
            out.append("});")
        out += ["", 'test("unknown codes are rejected", () => {',
                f'  assert.throws(() => m.{self.fn(sk.tables[0].noun)}("nope"));', "});"]
        return "\n".join(out) + "\n"

    def check_script(self):
        c = self.conv
        parts = []
        if c.finish_line:
            parts.append("node tools/codegen.mjs --verify")
        runner = "node --test test/*.test.mjs"
        if c.dead_end == "env_guard":
            runner = f"{self.skin.env}=test {runner}"
        elif c.dead_end in ("path_alias", "wrong_runner"):
            runner = "node --import ./tools/testing/setup.mjs --test test/*.test.mjs"
        parts.append(runner)
        return " && ".join(parts)

    def package_json(self):
        sk, c = self.skin, self.conv
        scripts = {"check": self.check_script()}
        if c.finish_line:
            scripts["codegen"] = "node tools/codegen.mjs"
        scripts["test"] = "node tools/retired.mjs" if c.instinct_violation else "npm run check"
        for m in c.decoys:
            name = sk.decoys[m]
            if m == "unused_target":
                scripts[name] = "node tools/bench.mjs"
            elif m == "lookalike_regen":
                scripts["gen:docs"] = "node tools/gen-docs.mjs"
            elif m == "lookalike_verify":
                scripts[name] = "node tools/lint.mjs"
        pkg = {"name": sk.repo, "version": "2.3.0", "private": True,
               "description": sk.description, "type": "module", "engines": {"node": ">=20.6"}, "scripts": scripts}
        return json.dumps(pkg, indent=2) + "\n"

    def repo_files(self):
        sk, c = self.skin, self.conv
        f = {}
        f["README.md"] = (f"# {sk.repo}\n\n{sk.description}\n\nWork items are tracked in {sk.tracker_phrase}.\n", False)
        f[".gitignore"] = ("node_modules/\n", False)
        f[".ci/pipeline.yml"] = (f"# The CI pipeline for {sk.repo}.\nsteps:\n  - name: check\n    run: {self.verify_cmd}\n",
                                 False)
        f["package.json"] = (self.package_json(), False)
        f["src/util.mjs"] = ("// Small shared helpers.\nexport function normalizeCode(code) {\n"
                             "  return code.trim().toUpperCase();\n}\n", False)
        for m in sk.modules:
            f[self.module_path(m)] = (self.module_text(m), False)
            f[f"test/{m}.test.mjs"] = (self.test_text(m), False)
        if c.dead_end == "path_alias":
            f["jsconfig.json"] = (json.dumps({"compilerOptions": {"baseUrl": ".", "paths": {f"{sk.scope}/*": ["src/*"]}}},
                                             indent=2) + "\n", False)
            f["tools/testing/aliases.mjs"] = (self.fill_tool(ALIAS_HOOKS, src='join(dirname(fileURLToPath(import.meta.url)), "..", "..", "src")'), False)
            f["tools/testing/setup.mjs"] = (self.fill_tool(REGISTER, hooks="./aliases.mjs"), False)
        elif c.dead_end == "env_guard":
            f["tools/testing/env.mjs"] = (f'if (process.env.{sk.env} !== "test") {{\n'
                                          f'  throw new Error("{self.dead_end_signature()}");\n}}\n', False)
        elif c.dead_end == "wrong_runner":
            f["tools/testing/fixtures.mjs"] = (f"if (!globalThis.{self.fixtures_global}) {{\n"
                                               f'  throw new Error("{self.dead_end_signature()}");\n}}\n'
                                               f"export const fixtures = globalThis.{self.fixtures_global};\n", False)
            f["tools/testing/setup.mjs"] = (f"// Loads the shared test fixtures (preloaded by npm run check).\n"
                                            f"globalThis.{self.fixtures_global} = Object.freeze({{ clock: \"2026-09-01T00:00:00Z\" }});\n",
                                            False)
        if c.instinct_violation:
            f["tools/retired.mjs"] = (f'console.error("{self.instinct_signature()}");\nprocess.exit(1);\n', False)
        if c.finish_line:
            for tab in sk.tables:
                f[f"registry/{tab.name}.csv"] = (self.csv_text(tab), False)
            f[self.reader_path()] = (self.reader_text(), False)
            f[f"test/{sk.registry_module}.test.mjs"] = (self.reader_test_text(), False)
            f["tools/codegen.mjs"] = (CODEGEN, True)
        if c.lookup:
            up = ", ".join(['".."'] * sk.tool.count("/"))
            f[sk.tool] = (self.fill_tool(LOOKUP, up=up), True)
        for m in c.decoys:
            name = sk.decoys[m]
            if m == "unused_target":
                f["tools/bench.mjs"] = ("// Micro-benchmarks for the hot helpers (kept for release notes).\n"
                                        "let total = 0;\nfor (let i = 0; i < 1000; i += 1) total += i;\n"
                                        'console.log("bench: 1000 runs done");\n', False)
            elif m == "lookalike_regen":
                f["tools/gen-docs.mjs"] = ("// Regenerates the API docs. They moved to the docs site in 2025, so\n"
                                           "// there is nothing left to generate in this repository.\n"
                                           'console.log("gen:docs: the API docs are built by the docs site, nothing to generate");\n',
                                           False)
            elif m == "lookalike_verify":
                f["tools/lint.mjs"] = ("// A light lint: every source file must end with a newline.\n"
                                       'import { readdirSync, readFileSync } from "node:fs";\n'
                                       'const bad = readdirSync("src").filter((f) => f.endsWith(".mjs") && !readFileSync(`src/${f}`, "utf8").endsWith("\\n"));\n'
                                       'if (bad.length) { console.error(`lint: missing final newline in ${bad.join(", ")}`); process.exit(1); }\n'
                                       'console.log("lint: ok");\n', False)
            elif m == "legacy_script":
                f[f"tools/{name}.mjs"] = ("// Legacy sync with the old yard system. The system was retired, so this is\n"
                                          "// a no-op kept for old runbooks.\n"
                                          f'console.log("{name}: the target was retired, nothing to do");\n', False)
        return f

    def generated_registry(self, root):
        """Mirror of tools/codegen.mjs render() (selfcheck proves they agree via `codegen --verify`)."""
        out = ["// Generated by tools/codegen.mjs from registry/*.csv. Do not edit by hand.", "",
               "export const TABLES = Object.freeze({"]
        for path in sorted((root / "registry").glob("*.csv"), key=lambda p: p.name):
            lines = [line for line in path.read_text().splitlines() if line.strip()]
            header = [h.strip() for h in lines[0].split(",")]
            rows = {}
            for line in lines[1:]:
                cells = [c.strip() for c in line.split(",")]
                rows[cells[0].upper()] = {h: (int(v) if v.isdigit() else v)
                                          for h, v in zip(header, cells + [""] * len(header)) if h != "code"}
            out.append(f"  {json.dumps(path.stem)}: Object.freeze({{")
            for code in sorted(rows):
                fields = ", ".join(f"{json.dumps(k)}: {json.dumps(rows[code][k])}" for k in sorted(rows[code]))
                out.append(f"    {json.dumps(code)}: Object.freeze({{ {fields} }}),")
            out.append("  }),")
        out += ["});", ""]
        return "\n".join(out)

    def hidden_test(self, t):
        sk = self.skin
        name = f"{t.id}.test.mjs"
        head = ['// Hidden check. Kept outside the repository; copied in only while scoring.',
                'import test from "node:test";', 'import assert from "node:assert/strict";']
        if t.kind == "registry":
            rt = t.registry
            tab = self.table(rt.table)
            head += [f'import * as m from "../src/{sk.registry_module}.mjs";', "",
                     f'test("hidden {t.id}: {self.fn(tab.noun)} {rt.code}", () => {{',
                     f"  for (const code of [{json.dumps(rt.code)}, {json.dumps(' ' + rt.code.lower() + ' ')}]) {{",
                     f"    const row = m.{self.fn(tab.noun)}(code);"]
            for k, v in rt.values.items():
                head.append(f"    assert.equal(row.{k}, {json.dumps(self.typed(v))});")
            head += ["  }", "});"]
            return name, "\n".join(head) + "\n"
        head += [f'import * as m from "../src/{t.module}.mjs";', "",
                 f'test("hidden {t.id}: {self.fname(t.template)}", () => {{', self.indent(self.test_body(t.template)), "});"]
        return name, "\n".join(head) + "\n"

    def hidden_count(self, text):
        return sum(1 for line in text.splitlines() if line.startswith("test("))

    def pristine_files(self):
        sk = self.skin
        setup = [f"// The scorer's own setup: satisfies every guard the sandbox may have.",
                 f"globalThis.{self.fixtures_global} = Object.freeze({{ clock: \"2026-09-01T00:00:00Z\" }});"]
        out = {}
        if self.conv.dead_end == "path_alias":
            out["aliases.mjs"] = self.fill_tool(ALIAS_HOOKS, src='join(process.cwd(), "src")')
            setup.append(self.fill_tool(REGISTER, hooks="./aliases.mjs"))
        out["setup.mjs"] = "\n".join(setup) + "\n"
        if self.conv.finish_line:
            out["codegen.mjs"] = CODEGEN
        return out

    def scoring(self):
        return {
            "ci": ["npm", "run", "check"],
            "hidden_dest": "test/hidden-{task}.test.mjs",
            "explicit": ["{node}", "--import", "{bundle}/pristine/setup.mjs", "--test", "--test-reporter=tap", "{dest}"],
            "format": "tap",
            "env": {self.skin.env: "test"},
            "ran_marker": "hidden {task}",
            "stale": ["{node}", "{bundle}/pristine/codegen.mjs", "--verify", "--root", "{sandbox}"] if self.conv.finish_line else None,
            "stale_marker": "is out of date with registry",
            "scrub_env": [self.skin.env],
        }

    def classify(self):
        tool = self.skin.tool.rsplit("/", 1)[-1]
        return {"lookup": [tool], "regen": ["npm run codegen", "tools/codegen.mjs"],
                "verify": ["npm test", "npm run test", "npm run check", "node --test", "--test ", "npm t "],
                "bash_edit": ["sed -i", "perl -pi", "cat >", "cat <<", "tee ", "> src/", ">src/", "> registry/",
                              ">registry/", ">> registry/", "writeFileSync"],
                "check_flags": ["--verify"]}
