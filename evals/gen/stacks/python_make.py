DEPS_TOOL = '''#!/usr/bin/env python3
"""Refresh requirements.lock from requirements.txt (what `make deps` runs). Offline: it records the
pins and their digest; installing them is the environment's business.

  python3 tools/deps.py            write requirements.lock
  python3 tools/deps.py --check    fail if requirements.lock is out of date
"""
import hashlib
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent


def render():
    text = (ROOT / "requirements.txt").read_text()
    pins = sorted(line.strip() for line in text.splitlines() if line.strip() and not line.startswith("#"))
    digest = hashlib.sha256(text.encode()).hexdigest()
    lines = ["# Generated by tools/deps.py from requirements.txt. Do not edit by hand.", f"# sha256 {digest}", *pins]
    return "".join(line + "\\n" for line in lines)


def main(argv):
    target = ROOT / "requirements.lock"
    if "--check" in argv:
        if not target.exists() or target.read_text() != render():
            print("@@signature@@", file=sys.stderr)
            return 1
        return 0
    target.write_text(render())
    print("wrote requirements.lock")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
'''


class PythonMake(Stack):
    NAME = "python-make"
    LANG = "py"
    DEAD_END_MODES = ("env_guard", "wrong_runner")

    verify_cmd = "make check"
    regen_cmd = "make gen"
    instinct_cmd = "make test"
    scope_cmd = "make -C packages/{part} check"
    deps_cmd = "make deps"

    @property
    def flag(self):
        return f"__{self.skin.pkg}_testkit__"

    # ------------------------------------------------------------------ naming

    def module_path(self, module):
        return f"{self.skin.pkg}/{module}.py"

    def reader_path(self):
        return f"{self.skin.pkg}/{self.skin.registry_module}.py"

    def generated_path(self):
        return f"{self.skin.pkg}/generated/registry.py"

    def package_path(self, package):
        return f"packages/{package}/core.py"

    # ------------------------------------------------------------------ commands and signatures

    def dead_end_runner(self):
        return "python3 -m unittest"

    def dead_end_variants(self):
        return ["python3 -m unittest", "python3 -m unittest discover -s tests", "python3 -m unittest -v"]

    def dead_end_signature(self):
        if self.conv.dead_end == "env_guard":
            return f"RuntimeError: {self.skin.env} is not set, run the suite with 'make check'"
        return "error: the test fixtures are not loaded, this suite runs through tools/testkit.py (make check)"

    def dead_end_notes(self):
        if self.conv.dead_end == "env_guard":
            return (f"tests/__init__.py aborts unless {self.skin.env}=test, which only `make check` sets. Plain "
                    f"unittest fails at once; `{self.skin.env}=test python3 -m unittest` would work (an environment "
                    f"fix). The working command is declared in .ci/pipeline.yml.")
        return ("tests/__init__.py aborts unless tools/testkit.py loaded the fixtures, so any generic runner fails; "
                "only `make check` works. The working command is declared in .ci/pipeline.yml.")

    def instinct_signature(self):
        return "error: 'make test' is retired, the suite runs with 'make check'"

    def deps_signature(self):
        return "error: requirements.lock is out of date with requirements.txt, run 'make deps'"

    def stale_signature(self):
        return f"error: {self.generated_path()} is out of date with registry/*.csv, run 'make gen'"

    def decoy_command(self, mode):
        name = self.skin.decoys[mode]
        if mode == "legacy_script":
            return f"./scripts/{name}"
        return f"make {name}"

    # ------------------------------------------------------------------ files

    def shaped_lookup(self, text):
        """Ids of other shapes are matched case-insensitively and may be typed with a leading `#`."""
        if self.plan.spec.get("id_shape", "prefix_dash") == "prefix_dash":
            return text
        old = ('    key = ids[0].strip().upper()\n'
               '    item = next((x for x in load() if x["id"] == key), None)\n')
        new = ('    key = ids[0].strip().lstrip("#").lower()\n'
               '    item = next((x for x in load() if x["id"].lower() == key), None)\n')
        assert old in text
        return text.replace(old, new)

    def fill_tool(self, text):
        sk = self.skin
        return bugs.fill(text, pkg=sk.pkg, flag=self.flag, env=sk.env, phrase=sk.tracker_phrase,
                         usage=sk.tool.rsplit("/", 1)[-1], depth=sk.tool.count("/"), store=sk.store, magic=sk.magic)

    # ------------------------------------------------------------------ Track G G3 kinds

    def package_task(self, package):
        return next((t for t in self.plan.tasks if t.kind == "scoped" and t.package == package), None)

    def package_text(self, package):
        """packages/<name>/core.py: a version helper, and the scoped task's function (bugged)."""
        t = self.package_task(package)
        head = f'"""The {package} package of {self.skin.repo}."""\n'
        if t and t.template == "ci_lookup":
            head += f"from {self.skin.pkg}.util import normalize_code\n"
        body = [f'def version():\n    return "1.{len(package)}"\n']
        if t:
            body.append(self.function_code(t.template, True))
        return head + "\n\n" + "\n\n".join(body)

    def package_test_text(self, package):
        return ("import unittest\n\n"
                f"from packages.{package} import core\n\n\n"
                f"class {package.capitalize()}Test(unittest.TestCase):\n"
                "    def test_version(self):\n"
                f"        self.assertEqual(core.version(), \"1.{len(package)}\")\n")

    def package_makefile(self, package):
        # From the repository root, so the package imports as `packages.<name>`.
        return (".PHONY: check\n\ncheck:\n"
                f"\t@cd ../.. && python3 -m unittest -q packages.{package}.test_core\n")

    def deps_lock(self):
        """requirements.lock as tools/deps.py writes it (the tool's own renderer, on a scratch root)."""
        import tempfile
        from pathlib import Path
        ns = {"__name__": "deps", "__file__": "tools/deps.py"}
        exec(compile(bugs.fill(DEPS_TOOL, signature=self.deps_signature()), "deps.py", "exec"), ns)
        with tempfile.TemporaryDirectory() as d:
            (Path(d) / "requirements.txt").write_text(self.requirements_text())
            ns["ROOT"] = Path(d)
            return ns["render"]()

    def module_text(self, module):
        sk = self.skin
        ids = self.plan.layout[module]
        head = f'"""{module.capitalize()} helpers for {sk.repo}."""\n'
        if "ci_lookup" in ids:
            head += f"from {sk.pkg}.util import normalize_code\n"
        funcs = [self.function_code(t, t in self.plan.bugged) for t in ids]
        return head + "\n\n" + "\n\n".join(funcs)

    def reader_text(self):
        sk = self.skin
        out = [f'"""Registry lookups. The tables live in registry/*.csv; this module reads the generated copy."""',
               f"from {sk.pkg}.generated.registry import TABLES", f"from {sk.pkg}.util import normalize_code", "", ""]
        for tab in sk.tables:
            out += [f"def {tab.noun}(code):", f'    return _row("{tab.name}", code)', "", ""]
        out += ["def _row(table, code):", "    row = TABLES[table].get(normalize_code(code))", "    if row is None:",
                '        raise KeyError(f"unknown {table} code: {code}")', "    return dict(row)", ""]
        return "\n".join(out)

    def indent(self, body, n=8):
        return "\n".join((" " * n + line) if line else "" for line in body.splitlines())

    def test_text(self, module):
        sk = self.skin
        cls = "".join(w.capitalize() for w in module.split("_"))
        out = ["import unittest", "", "import tests  # noqa: F401  (the suite's shared setup)",
               f"from {sk.pkg} import {module} as m", "", "", f"class {cls}Test(unittest.TestCase):",
               "    def test_module_loads(self):", "        self.assertTrue(m.__doc__)"]
        for t in self.plan.layout[module]:
            if t in self.plan.bugged:
                continue
            out += ["", f"    def test_{self.skin.functions[t][0]}(self):", self.indent(self.test_body(t))]
        return "\n".join(out) + "\n"

    def reader_test_text(self):
        sk = self.skin
        out = ["import unittest", "", "import tests  # noqa: F401  (the suite's shared setup)",
               f"from {sk.pkg} import {sk.registry_module} as m", "", "", "class RegistryTest(unittest.TestCase):"]
        for tab in sk.tables:
            row = self.stable_row(tab)
            out += [f"    def test_{tab.noun}(self):", f"        row = m.{tab.noun}({row[0].lower()!r})"]
            for c, v in zip(tab.columns[1:], row[1:]):
                out.append(f"        self.assertEqual(row[{c!r}], {self.typed(v)!r})")
            out.append("")
        out += ["    def test_unknown_code(self):", "        with self.assertRaises(KeyError):",
                f"            m.{sk.tables[0].noun}('nope')"]
        return "\n".join(out) + "\n"

    def guard_text(self):
        sk = self.skin
        mode = self.conv.dead_end
        if mode == "env_guard":
            return ('"""Shared test setup."""\nimport os\nimport sys\n\n'
                    f'if os.environ.get("{sk.env}") != "test":\n'
                    f'    sys.stderr.write("{self.dead_end_signature()}\\n")\n'
                    "    sys.stderr.flush()\n    os._exit(2)\n")
        if mode == "wrong_runner":
            return ('"""Shared test setup: the fixtures come from tools/testkit.py."""\nimport builtins\nimport os\nimport sys\n\n'
                    f'if not getattr(builtins, "{self.flag}", False):\n'
                    f'    sys.stderr.write("{self.dead_end_signature()}\\n")\n'
                    "    sys.stderr.flush()\n    os._exit(2)\n")
        return '"""Shared test setup."""\n'

    def makefile(self):
        sk, c = self.skin, self.conv
        env = f"{sk.env}=test " if c.dead_end == "env_guard" else ""
        targets = ["check"] + (["gen"] if c.finish_line else []) + (["deps"] if c.env_sync else []) + ["test"]
        decoy_targets = [sk.decoys[m] for m in c.decoys if m != "legacy_script"]
        lines = [f".PHONY: {' '.join(targets + decoy_targets)}", "", "check:"]
        if c.finish_line:
            lines.append("\t@python3 tools/gen.py --check")
        if c.env_sync:
            lines.append("\t@python3 tools/deps.py --check")
        lines += [f"\t@{env}python3 tools/testkit.py", ""]
        if c.finish_line:
            lines += ["gen:", "\t@python3 tools/gen.py", ""]
        if c.env_sync:
            lines += ["deps:", "\t@python3 tools/deps.py", ""]
        if c.instinct_violation:
            lines += ["test:", f"\t@echo \"{self.instinct_signature()}\" >&2; exit 1", ""]
        else:
            lines += ["test: check", ""]
        for m in c.decoys:
            name = sk.decoys[m]
            if m == "unused_target":
                lines += [f"{name}:", "\t@python3 tools/bench.py", ""]
            elif m == "lookalike_regen":
                lines += [f"{name}:", "\t@python3 tools/proto.py", ""]
            elif m == "lookalike_verify":
                lines += [f"{name}:", f"\t@python3 -m py_compile {sk.pkg}/*.py tools/*.py && echo \"lint: ok\"", ""]
        return "\n".join(lines)

    def repo_files(self):
        sk, c = self.skin, self.conv
        f = {}
        f["README.md"] = (f"# {sk.repo}\n\n{sk.description}\n\nWork items are tracked in {sk.tracker_phrase}. "
                          f"Development tasks are defined in the Makefile.\n", False)
        f[".gitignore"] = ("__pycache__/\n*.pyc\n", False)
        steps = ""
        if c.env_sync:
            steps += f"  - name: deps\n    run: {self.deps_cmd}\n"
        if c.sequence:
            steps += f"  - name: generate\n    run: {self.regen_cmd}\n"
        steps += f"  - name: check\n    run: {self.verify_cmd}\n"
        if c.scope:
            for p in sk.packages:
                steps += f"  - name: {p}\n    run: {self.scope_cmd.replace('{part}', p)}\n"
        f[".ci/pipeline.yml"] = (f"# The CI pipeline for {sk.repo}.\nsteps:\n{steps}", False)
        f["Makefile"] = (self.makefile(), False)
        f[f"{sk.pkg}/__init__.py"] = (f'"""{sk.description}"""\n', False)
        f[f"{sk.pkg}/util.py"] = ('"""Small shared helpers."""\n\n\ndef normalize_code(code):\n'
                                  "    return code.strip().upper()\n", False)
        for m in sk.modules:
            f[self.module_path(m)] = (self.module_text(m), False)
            f[f"tests/test_{m}.py"] = (self.test_text(m), False)
        f["tests/__init__.py"] = (self.guard_text(), False)
        f["tools/testkit.py"] = (self.fill_tool(TESTKIT), True)
        if c.finish_line:
            for tab in sk.tables:
                f[f"registry/{tab.name}.csv"] = (self.csv_text(tab), False)
            f[f"{sk.pkg}/generated/__init__.py"] = ("", False)
            f[self.reader_path()] = (self.reader_text(), False)
            f[f"tests/test_{sk.registry_module}.py"] = (self.reader_test_text(), False)
            f["tools/gen.py"] = (self.fill_tool(GEN_TOOL), True)
        if c.lookup:
            f[sk.tool] = (self.shaped_lookup(self.fill_tool(LOOKUP)), True)
        if c.scope:
            f["packages/__init__.py"] = ('"""Packages with their own test suites."""\n', False)
            for p in sk.packages:
                f[f"packages/{p}/__init__.py"] = ("", False)
                f[self.package_path(p)] = (self.package_text(p), False)
                f[f"packages/{p}/test_core.py"] = (self.package_test_text(p), False)
                f[f"packages/{p}/Makefile"] = (self.package_makefile(p), False)
        if c.env_sync:
            f["requirements.txt"] = (self.requirements_text(), False)
            f["requirements.lock"] = (self.deps_lock(), False)
            f["tools/deps.py"] = (bugs.fill(DEPS_TOOL, signature=self.deps_signature()), True)
        for m in c.decoys:
            name = sk.decoys[m]
            if m == "unused_target":
                f["tools/bench.py"] = ('"""Micro-benchmarks for the hot helpers (kept for release notes)."""\n'
                                       'import timeit\n\n'
                                       'n = timeit.timeit("sum(range(100))", number=1000)\n'
                                       'print("bench: 1000 runs done")\n', False)
            elif m == "lookalike_regen":
                f["tools/proto.py"] = ('"""Regenerate the protocol stubs. The stubs moved to the shared schema '
                                       'repository in 2025, so there is nothing left to generate here."""\n'
                                       'print("proto: no protocol files in this repository, nothing to generate")\n',
                                       False)
            elif m == "legacy_script":
                f[f"scripts/{name}"] = ("#!/usr/bin/env python3\n\"\"\"Legacy export to the old warehouse. The "
                                        "warehouse was retired, so this is a no-op kept for old runbooks.\"\"\"\n"
                                        f"print(\"{name}: the target was retired, nothing to do\")\n", True)
        return f

    def generated_registry(self, root):
        ns = {}
        exec(compile(self.fill_tool(GEN_TOOL), "gen.py", "exec"), ns)  # the tool's own renderer
        return ns["render"](root)

    def hidden_test(self, t):
        sk = self.skin
        name = f"test_hidden_{slug(t.id)}.py"
        cls = "Hidden" + "".join(w.capitalize() for w in slug(t.id).split("_"))
        head = [f'"""Hidden check for {t.id}. Kept outside the repository; copied in only while scoring."""',
                "import unittest", ""]
        if t.kind == "scoped":
            head += [f"from packages.{t.package} import core as m", "", "", f"class {cls}(unittest.TestCase):",
                     f"    def test_{sk.functions[t.template][0]}(self):", self.indent(self.test_body(t.template))]
            return name, "\n".join(head) + "\n"
        if t.kind == "deps":
            lib, ver = t.dep
            head = [head[0], "import hashlib", "import unittest", "from pathlib import Path", "", "",
                    f"class {cls}(unittest.TestCase):",
                    f"    def test_{lib.replace('-', '_')}_pinned_and_locked(self):",
                    "        text = Path('requirements.txt').read_text()",
                    f"        self.assertIn('{lib}=={ver}', text.splitlines())",
                    "        lock = Path('requirements.lock').read_text()",
                    "        self.assertIn('# sha256 ' + hashlib.sha256(text.encode()).hexdigest(), lock)",
                    f"        self.assertIn('{lib}=={ver}', lock.splitlines())"]
            return name, "\n".join(head) + "\n"
        if t.kind == "registry":
            rt = t.registry
            tab = self.table(rt.table)
            head += [f"from {sk.pkg} import {sk.registry_module} as m", "", "", f"class {cls}(unittest.TestCase):",
                     f"    def test_{tab.noun}_{rt.code.lower()}(self):"]
            body = [f"        for code in ({rt.code!r}, {(' ' + rt.code.lower() + ' ')!r}):",
                    f"            row = m.{tab.noun}(code)"]
            for k, v in rt.values.items():
                body.append(f"            self.assertEqual(row[{k!r}], {self.typed(v)!r})")
            return name, "\n".join(head + body) + "\n"
        head += [f"from {sk.pkg} import {t.module} as m", "", "", f"class {cls}(unittest.TestCase):",
                 f"    def test_{sk.functions[t.template][0]}(self):", self.indent(self.test_body(t.template))]
        return name, "\n".join(head) + "\n"

    def hidden_count(self, text):
        return text.count("    def test_")

    def pristine_files(self):
        out = {"runhidden.py": self.fill_tool(RUNHIDDEN)}
        if self.conv.finish_line:
            out["gen.py"] = self.fill_tool(GEN_TOOL)
        return out

    def scoring(self):
        # score.py names the copied hidden test after the task's slug, which is not a module name
        # for ids of other shapes (`bil/412`); those use one fixed name (one task is scored at a time).
        name = "{slug}" if self.plan.spec.get("id_shape", "prefix_dash") == "prefix_dash" else "item"
        return {
            "ci": ["make", "check"],
            "hidden_dest": f"tests/test_hidden_{name}.py",
            "explicit": ["{python}", "{bundle}/pristine/runhidden.py", "{sandbox}", f"tests.test_hidden_{name}"],
            "format": "unittest",
            "ran_marker": f"test_hidden_{name}",
            "stale": ["{python}", "{bundle}/pristine/gen.py", "--check", "--root", "{sandbox}"] if self.conv.finish_line else None,
            "stale_marker": "is out of date with registry",
            "scrub_env": [self.skin.env],
        }

    def classify(self):
        tool = self.skin.tool.rsplit("/", 1)[-1]
        return {"lookup": [tool], "regen": ["make gen", "tools/gen.py"],
                "verify": ["unittest", "make test", "make check", "pytest", "testkit"],
                "bash_edit": ["sed -i", "cat >", "cat <<", "tee ", "write_text(", f"> {self.skin.pkg}/", "> registry/",
                              ">> registry/", f">{self.skin.pkg}/"],
                "check_flags": ["--check"]}
